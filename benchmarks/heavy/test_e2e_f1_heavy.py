#!/usr/bin/env python3
"""L0-heavy -- the half of `tools/test_e2e.py` that needs the hidden reference
or a child interpreter.

`benchmarks/heavy/README.md` gives the seam: a test belongs here when it starts
a child, needs a corpus or a B-rep, or runs a job more than once. Both apply.
The reference is generated by a pinned third-party generator into the project
tree and is `EXTERNAL_ONLY`, so it is never vendored and never present in CI;
and `make_3mf.py` is a script, so exercising the repository's real 3MF writer
costs an interpreter.

**Why this file is the one that matters.** `tools/test_e2e.py` proves the
predicates on a bin `tools/f1_candidate.py` wrote, and a predicate that only
ever met geometry written to satisfy it is a tautology. Here the same
predicates meet a solid nobody in this repository authored -- produced by
`cqgridfinity` at a pinned commit from the published grid standard -- and it
has to pass all ten. That is the second state, and without it the L0 half
distinguishes nothing.

F1 is `required_hosted: false`, so a missing reference is an explicit skip that
names how to make it, rather than a silent pass. The brief's section 1.4 allows
that only for an optional track and this fixture is declared as one.
"""
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
# Bare names, for the module-identity reason `test_blind_corpus.py` records at
# length: `from tools import e2e` builds a second module object for the same
# file, and anything patched on one is invisible to the other.
sys.path.insert(0, str(REPO / "tools"))

import e2e  # noqa: E402

SPEC = e2e.fixture()
GEOMETRY = SPEC["geometry"]

# The comparison is run at a lower sample count than the fixture freezes. The
# estimator is the same and only its standard error widens, and every
# comparison here is a solid against itself, where the answer is zero to eleven
# decimal places -- so the sample count buys nothing and costs about thirty
# seconds a call. The frozen count is what the calibration record and the real
# run used.
FAST = json.loads(json.dumps(GEOMETRY))
FAST["reference_comparison"]["samples"] = 3000
FAST["reference_comparison"]["probe_samples"] = 300
FAST["three_mf"]["samples"] = 2000


def _reference() -> Path | None:
    try:
        return e2e.reference_path(SPEC)
    except e2e.ReferenceUnavailable:
        return None


HAVE = _reference()
WHY = (f"{SPEC['id']}'s reference is not on this machine. It is generated, not "
       f"fetched: {SPEC['reference']['generator']['install']} then "
       f"{SPEC['reference']['generator']['call']}, normalised through "
       f"mesh_io.normalize_mesh, into "
       f"{SPEC['reference']['root']['default']}/{SPEC['reference']['path']}.")

_MEASURED: dict[str, object] = {}


def measured() -> dict[str, object]:
    if not _MEASURED:
        mesh = e2e.load(HAVE)
        found = e2e.features(mesh, GEOMETRY)
        _MEASURED.update(mesh=mesh, features=found,
                         rows={row["predicate"]: row
                               for row in e2e.predicates(found, GEOMETRY)})
    return _MEASURED


@unittest.skipUnless(HAVE, WHY)
class TheHiddenReferencePassesEveryHardPredicateTest(unittest.TestCase):
    """The second state. Geometry nobody here wrote, through the same ten rows.

    A failure in this class is not a reference problem; it is a predicate that
    was fitted to `tools/f1_candidate.py` and does not describe the standard.
    """

    def test_every_hard_predicate_passes_on_the_reference(self) -> None:
        failed = [name for name, row in measured()["rows"].items()  # type: ignore[union-attr]
                  if not row["passes"]]
        self.assertEqual([], failed)

    def test_the_reference_and_the_synthetic_bin_are_not_the_same_solid(self) -> None:
        """Both pass, and they are different geometry. Otherwise the two states
        are one state and neither distinguishes anything."""
        sys.path.insert(0, str(REPO / "tools"))
        import f1_candidate

        self.assertNotAlmostEqual(float(f1_candidate.HEIGHT_MM),
                                  measured()["features"]["height_mm"],
                                  places=2)
        self.assertNotAlmostEqual(float(f1_candidate.LIP_INSET_MM),
                                  measured()["rows"]["stack_lip_present"]["measured"],
                                  places=2)


@unittest.skipUnless(HAVE, WHY)
class TheReferenceScoresCleanAgainstItselfTest(unittest.TestCase):
    """The only case anybody runs by hand, and the one a broken scorer passes.

    `tools/test_blind.py` makes the same argument about its own scorer: a
    comparison that reported agreement whatever it was given is
    indistinguishable from a working one until something disagrees. The
    disagreeing cases are in the L0 half; this is the agreement case.
    """

    def test_registration_recovers_the_identity_pose_with_det_plus_one(self) -> None:
        mesh = measured()["mesh"]
        found = e2e.register(
            mesh.copy(), mesh,
            samples=FAST["reference_comparison"]["samples"],
            seed=FAST["reference_comparison"]["seed"],
            band_mm=FAST["reference_comparison"]["band_mm"],
            probe_samples=FAST["reference_comparison"]["probe_samples"])
        self.assertEqual(1.0, found["determinant"])
        self.assertLess(found["distance"]["p99_mm"], 1e-6)
        rows = {row["predicate"]: row
                for row in e2e.comparison_rows(found, FAST)}
        self.assertTrue(all(row["passes"] for row in rows.values()))


@unittest.skipUnless(HAVE, WHY)
class TheRepositorysOwnThreeMfWriterIsReadableTest(unittest.TestCase):
    """`make_3mf.py`'s real output through `e2e.read_three_mf`.

    The L0 half writes its own archive, because it may not start a child. That
    leaves one gap and this closes it: the format the L0 test assumes has to be
    the format the repository actually emits, or both halves agree with each
    other and neither agrees with the deliverable.

    The reason the reader exists at all -- `docs/defects.md` D3 -- is pinned in
    `tools/test_e2e.py` instead, against `pyproject.toml` rather than against
    whatever extras this machine happens to have selected.
    """

    def test_the_written_archive_places_exactly_the_one_body(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            out = Path(raw) / "bin.3mf"
            done = subprocess.run(
                [sys.executable, str(REPO / "skills/3d-modeling/scripts/make_3mf.py"),
                 str(out), f"Bin={HAVE}"],
                capture_output=True, text=True, check=False)
            self.assertEqual(0, done.returncode, done.stderr)
            read = e2e.read_three_mf(out)
            rows = {row["predicate"]: row for row in
                    e2e.three_mf_rows(out, measured()["mesh"], FAST)}
        self.assertEqual(1, read["build_items"])
        self.assertEqual(1, read["printable_bodies"])
        self.assertEqual("millimeter", read["unit"])
        self.assertTrue(all(row["passes"] for row in rows.values()), rows)


@unittest.skipUnless(HAVE, WHY)
class TheWholeArmRunsEndToEndTest(unittest.TestCase):
    """Request out, deliverables in, one report. The shell, not the predicates.

    Scored with the reference *as the candidate*, which is the only candidate
    available without an authoring turn. That makes this a test of the
    plumbing -- request materialisation, the leak audit, the two gates, the
    clock split -- and explicitly not evidence that any designer can pass F1.
    """

    def test_the_shell_produces_a_bound_report_with_the_clock_split(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            request = e2e.write_request(SPEC, root)
            fast = json.loads(json.dumps(SPEC))
            fast["geometry"] = FAST
            report = e2e.score(HAVE, None, fast, request_dir=request,
                               design_path_seconds=0.0,
                               authoring_root="the reference itself; no "
                                              "authoring turn was run")
        self.assertEqual("CAD_PASS", report["verdict"])
        self.assertEqual(SPEC["reference"]["sha256"], report["reference_sha256"])
        self.assertEqual(["extent_y"], report["request_audit"]["declared"])
        # The two clocks are reported apart and never summed, which is what the
        # reviewer asked for: a blended number cannot say whether a slow run is
        # an expensive benchmark or expensive CAD, and those have different
        # remedies.
        self.assertGreater(report["timings"]["harness_seconds"], 0.0)
        self.assertEqual(0.0, report["timings"]["design_path_seconds"])
        self.assertIn("never summed", report["timings"]["note"])

    def test_a_report_names_every_hard_predicate_it_decided_on(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            fast = json.loads(json.dumps(SPEC))
            fast["geometry"] = FAST
            report = e2e.score(HAVE, None, fast,
                               request_dir=e2e.write_request(SPEC, Path(raw)))
        names = [row["predicate"] for row in report["hard_predicates"]]
        self.assertIn("reference_surface_distance_p99_mm", names)
        self.assertIn("registration_is_a_proper_rotation", names)
        self.assertEqual(len(names), len(set(names)))
        self.assertIn("| `stack_lip_present` | PASS |", e2e.render(report))


if __name__ == "__main__":
    unittest.main()
