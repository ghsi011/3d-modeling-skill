def _proper_rotations():
    """The 24 proper rotations of a cuboid, and not the 24 improper ones.

    Generated by filtering the 48 signed permutation matrices on
    `det = +1`, so the reflections are absent by construction. Brief section 4:
    *a mirrored part must not become a PASS because a fitter found a
    reflection.* A tolerance-based rule would be the wrong instrument -- a
    reflection is not a near miss of a rotation, it is a different group coset,
    and the determinant is exactly one or exactly minus one.
    """
    import numpy as np

    out = []
    for perm in itertools.permutations(range(3)):
        for signs in itertools.product((1.0, -1.0), repeat=3):
            matrix = np.zeros((3, 3))
            for row, col in enumerate(perm):
                matrix[row, col] = signs[row]
            if round(float(np.linalg.det(matrix))) == 1:
                out.append(matrix)
    return out


def undetermined(points, mask: dict[str, float] | None):
    """Which sampled points sit on a surface the request does not determine.

    Revision 2's answer to the reviewer's ruling. A hard reference-distance
    predicate may judge a surface only where request-side facts fix it, and two
    regions of this part are not fixed by anything the request states:

    * **the tie between the feet and the body.** The published base profile is
      per grid unit and the published base height is one height unit, so
      somewhere in the 2.25 mm between the top of the profile and the top of the
      base the feet grow into one body -- and the publication does not say
      where. Measured on two independent implementations: the reference closes
      it in 0.25 mm, and run 02's candidate ramps it over the whole 2.25 mm
      because the body overhangs the feet by about 30 mm2 of flat ceiling and
      the brief forbids supports. Revision 2 judged this span and failed a
      conformant candidate for it; that is the defect run 02 found and revision
      3 removes.
    * **the internal floor transition.** The publication gives the floor height
      -- the base occupies the first height unit -- and says nothing about the
      fillet or chamfer that joins the floor to the walls. That it is genuinely
      undetermined is not an assumption: the same public file offers `r_f2 =
      2.8` for an internal fillet while the reference uses 1.1, so two readings
      of one source disagree. The mask covers the floor upward by the larger of
      the two, which is the largest internal radius the source contemplates.
    * **everything above the lip's published land.** The published lip ends in a
      1.9 mm chamfer that would open the socket to the full outer surface and
      leave the rim a knife edge at a 1.0 mm wall, so every implementation
      truncates it and the publication does not say by how much. Measured: the
      reference truncates that segment to 1.3 mm.

    Both bounds are computed from numbers the request states. The masked points
    are dropped as *queries* only; the other solid stays whole as the target, so
    a candidate that omitted a masked feature still shows the distance from the
    reference's side of it wherever that side is not itself masked.
    """
    import numpy as np

    keep = np.ones(len(points), dtype=bool)
    if not mask:
        return ~keep
    z = np.asarray(points, dtype=float)[:, 2]
    keep &= ~((z >= mask["tie_low_mm"]) & (z <= mask["tie_high_mm"]))
    keep &= ~((z >= mask["floor_low_mm"]) & (z <= mask["floor_high_mm"]))
    keep &= z <= mask["lip_land_top_mm"]
    return ~keep


def surface_distance(a, b, *, samples: int, seed: int, band_mm: float,
                     mask: dict[str, float] | None = None) -> dict[str, float]:
    """Bidirectional sampled surface distance between two meshes.

    Both directions, because a one-way nearest-neighbour score is blind in the
    direction that matters most here: every point of a bin with an extra
    protrusion still has a near neighbour on the bin without one, so A->B stays
    small while B->A does not. Brief section 4.6 requires both and this is why.

    Deterministic: the sample seed is frozen in the fixture, so two runs of the
    same pair produce the same distribution and a changed number means changed
    geometry.

    `mask` drops the query points on surfaces the request does not determine;
    see `undetermined`. It is reported rather than silently applied -- the
    retained and dropped counts are both in the result, because a mask that
    quietly dropped everything would leave a row that cannot fail.
    """
    return summarise(*sampled_distances(a, b, samples=samples, seed=seed),
                     band_mm=band_mm, mask=mask)


def sampled_distances(a, b, *, samples: int, seed: int):
    """Both directions' sample points and their distances, measured once.

    Split out from `surface_distance` so the masked row and the unmasked
    diagnostic are two summaries of **one** measurement rather than two
    measurements. Two passes would have doubled the most expensive call in the
    harness -- and worse, would have let the row and the diagnostic disagree
    about the same pair of solids, which is the one thing a diagnostic beside a
    verdict must not do.
    """
    import numpy as np
    import trimesh

    pa = trimesh.sample.sample_surface(a, samples, seed=seed)[0]
    pb = trimesh.sample.sample_surface(b, samples, seed=seed)[0]
    da = trimesh.proximity.closest_point(b, pa)[1]
    db = trimesh.proximity.closest_point(a, pb)[1]
    points = np.concatenate([np.asarray(pa, dtype=float),
                             np.asarray(pb, dtype=float)])
    distances = np.concatenate([np.asarray(da, dtype=float),
                                np.asarray(db, dtype=float)])
    return points, distances


def summarise(points, distances, *, band_mm: float,
              mask: dict[str, float] | None = None) -> dict[str, float]:
    """The distribution a predicate reads, over the points the mask retains."""
    import numpy as np

    drop = undetermined(points, mask)
    both = distances[~drop]
    if not both.size:
        raise E2EError(
            "the reference comparison retained no samples. A mask that removes "
            "the whole part leaves a row that cannot fail, which reads exactly "
            "like a row that holds.")
    return {
        "samples": int(both.size),
        "masked_out": int(drop.sum()),
        "median_mm": float(np.median(both)),
        "mean_mm": float(np.mean(both)),
        "p95_mm": float(np.percentile(both, 95)),
        "p99_mm": float(np.percentile(both, 99)),
        "max_mm": float(np.max(both)),
        "fraction_within_band": float(np.mean(both <= band_mm)),
    }


def _seat(mesh):
    """Put a solid on the plane it prints on, centred on its own footprint.

    The named datum this fixture registers to, and at revision 2 it replaced a
    bounding-box centroid. The request dimensions the base plug from the bottom
    of the foot upward and fixes the footprint, so those two facts *are* the
    datum: `z = 0` is the plane the bin stands on and the origin is the centre
    of the cell it drops into.

    Centroid centring was wrong here for a reason the run measured rather than
    imagined. Two bins that both implement the published lip may differ in
    overall height by up to the 1.9 mm the publication cannot fix, and a
    centroid fit turns half of that into a z offset applied to every surface --
    including the base plug, which the request now states exactly. The datum
    leaves that difference where it belongs, above the lip's land, where the
    mask removes it.
    """
    import numpy as np

    out = mesh.copy()
    low, high = out.bounds
    out.apply_translation(np.array([-(low[0] + high[0]) / 2.0,
                                    -(low[1] + high[1]) / 2.0,
                                    -low[2]], dtype=float))
    return out


def register(candidate, reference, *, samples: int, seed: int, band_mm: float,
             probe_samples: int = 1500, mask: dict[str, float] | None = None
             ) -> dict[str, Any]:
    """Translation to a named datum plus one proper rotation, chosen by distance.

    Each of the 24 proper rotations is applied to the candidate, both solids are
    seated on their own base plane and centred on their own footprint, the pose
    is scored on a cheap probe sample and the best is re-measured at full count.
    No scaling is fitted and no reflection is available, so a mirrored candidate
    cannot be rotated into agreement -- it is scored as the mismatch it is.

    The seat is applied *after* the rotation, because a rotation about the
    origin moves the base plane; seating first would leave the pose search
    comparing solids that are not standing on anything.
    """
    import numpy as np

    fixed = _seat(reference)
    want = np.asarray(reference.extents, dtype=float)
    have = np.asarray(candidate.extents, dtype=float)

    # Poses whose rotated bounding box does not match the reference's cannot be
    # the alignment, so they are not measured. This is a cost decision with a
    # correctness floor under it: when *no* pose matches -- a candidate with the
    # wrong extents, which is a thing the extents predicates report separately
    # -- every pose is tried, so the fallback is the full group rather than an
    # empty set and an exception.
    # Generous on purpose, and much wider than the acceptance band: this filter
    # decides which way up the part is, not whether it is right. A tolerance of
    # the acceptance band would drop the correct pose for a candidate that is
    # merely a millimetre off, and the fallback below would then measure all 24.
    slack = 0.05 * float(np.max(want))
    poses = [(index, rotation) for index, rotation
             in enumerate(_proper_rotations())
             if np.allclose(np.abs(rotation @ have), want, atol=slack)]
    if not poses:
        poses = list(enumerate(_proper_rotations()))

    best = None
    for index, rotation in poses:
        transform = np.eye(4)
        transform[:3, :3] = rotation
        moved = candidate.copy()
        moved.apply_transform(transform)
        moved = _seat(moved)
        probe = surface_distance(moved, fixed, samples=probe_samples, seed=seed,
                                 band_mm=band_mm, mask=mask)
        # The MEAN, not the median. Measured: a two percent single-axis scale --
        # a defect a metre away is visible in -- has a median distance of
        # 5e-15 mm, because most of a sampled surface still lands on the other
        # surface. The median cannot choose a pose; the mean separates the same
        # pair by five orders of magnitude.
        if best is None or probe["mean_mm"] < best[1]["mean_mm"]:
            best = (index, probe, transform, moved)
    index, _, transform, moved = best
    points, distances = sampled_distances(moved, fixed, samples=samples,
                                          seed=seed)
    full = summarise(points, distances, band_mm=band_mm, mask=mask)
    unmasked = summarise(points, distances, band_mm=band_mm)
    return {"pose_index": index,
            "rotation": [[float(v) for v in row] for row in transform[:3, :3]],
            "determinant": round(float(np.linalg.det(transform[:3, :3])), 9),
            "distance": full,
            # Demoted, not deleted. The ruling allows a contribution to be
            # masked OR demoted to diagnostic; the masked regions are still
            # measured and reported here, so a reader can see what the hard row
            # declined to judge instead of having to trust that it was small.
            "distance_unmasked": unmasked}


# --------------------------------------------------------------------------
# The hard predicates. Candidate-independent, and frozen before any run.
