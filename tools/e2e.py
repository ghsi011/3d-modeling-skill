def _proper_rotations():
    """The 24 proper rotations of a cuboid, and not the 24 improper ones.

    Generated by filtering the 48 signed permutation matrices on
    `det = +1`, so the reflections are absent by construction. Brief section 4:
    *a mirrored part must not become a PASS because a fitter found a
    reflection.* A tolerance-based rule would be the wrong instrument -- a
    reflection is not a near miss of a rotation, it is a different group coset,
    and the determinant is exactly one or exactly minus one.
    """
    import numpy as np

    out = []
    for perm in itertools.permutations(range(3)):
        for signs in itertools.product((1.0, -1.0), repeat=3):
            matrix = np.zeros((3, 3))
            for row, col in enumerate(perm):
                matrix[row, col] = signs[row]
            if round(float(np.linalg.det(matrix))) == 1:
                out.append(matrix)
    return out


def surface_distance(a, b, *, samples: int, seed: int, band_mm: float
                     ) -> dict[str, float]:
    """Bidirectional sampled surface distance between two meshes.

    Both directions, because a one-way nearest-neighbour score is blind in the
    direction that matters most here: every point of a bin with an extra
    protrusion still has a near neighbour on the bin without one, so A->B stays
    small while B->A does not. Brief section 4.6 requires both and this is why.

    Deterministic: the sample seed is frozen in the fixture, so two runs of the
    same pair produce the same distribution and a changed number means changed
    geometry.
    """
    import numpy as np
    import trimesh

    pa = trimesh.sample.sample_surface(a, samples, seed=seed)[0]
    pb = trimesh.sample.sample_surface(b, samples, seed=seed)[0]
    da = trimesh.proximity.closest_point(b, pa)[1]
    db = trimesh.proximity.closest_point(a, pb)[1]
    both = np.concatenate([np.asarray(da, dtype=float),
                           np.asarray(db, dtype=float)])
    return {
        "samples": int(both.size),
        "median_mm": float(np.median(both)),
        "mean_mm": float(np.mean(both)),
        "p95_mm": float(np.percentile(both, 95)),
        "p99_mm": float(np.percentile(both, 99)),
        "max_mm": float(np.max(both)),
        "fraction_within_band": float(np.mean(both <= band_mm)),
    }


def register(candidate, reference, *, samples: int, seed: int, band_mm: float,
             probe_samples: int = 1500) -> dict[str, Any]:
    """Translation plus one proper rotation, chosen by measured distance.

    The candidate is centred on its own bounding box and the reference on its
    own, then each of the 24 proper rotations is scored on a cheap probe sample
    and the best is re-measured at full count. No scaling is fitted and no
    reflection is available, so a mirrored candidate cannot be rotated into
    agreement -- it is scored as the mismatch it is.

    Centring on the bounding box rather than the centre of mass is deliberate:
    a centre of mass moves when a feature is removed, so a missing divider would
    partly hide itself by shifting the fit. A bounding box moves only when the
    envelope changes, which is a thing the extents predicate reports separately.
    """
    import numpy as np

    fixed = reference.copy()
    fixed.apply_translation(-reference.bounding_box.centroid)
    want = np.asarray(reference.extents, dtype=float)
    have = np.asarray(candidate.extents, dtype=float)

    # Poses whose rotated bounding box does not match the reference's cannot be
    # the alignment, so they are not measured. This is a cost decision with a
    # correctness floor under it: when *no* pose matches -- a candidate with the
    # wrong extents, which is a thing the extents predicates report separately
    # -- every pose is tried, so the fallback is the full group rather than an
    # empty set and an exception.
    # Generous on purpose, and much wider than the acceptance band: this filter
    # decides which way up the part is, not whether it is right. A tolerance of
    # the acceptance band would drop the correct pose for a candidate that is
    # merely a millimetre off, and the fallback below would then measure all 24.
    slack = 0.05 * float(np.max(want))
    poses = [(index, rotation) for index, rotation
             in enumerate(_proper_rotations())
             if np.allclose(np.abs(rotation @ have), want, atol=slack)]
    if not poses:
        poses = list(enumerate(_proper_rotations()))

    best = None
    for index, rotation in poses:
        moved = candidate.copy()
        moved.apply_translation(-candidate.bounding_box.centroid)
        transform = np.eye(4)
        transform[:3, :3] = rotation
        moved.apply_transform(transform)
        probe = surface_distance(moved, fixed, samples=probe_samples, seed=seed,
                                 band_mm=band_mm)
        # The MEAN, not the median. Measured: a two percent single-axis scale --
        # a defect a metre away is visible in -- has a median distance of
        # 5e-15 mm, because most of a sampled surface still lands on the other
        # surface. The median cannot choose a pose; the mean separates the same
        # pair by five orders of magnitude.
        if best is None or probe["mean_mm"] < best[1]["mean_mm"]:
            best = (index, probe, transform, moved)
    index, _, transform, moved = best
    full = surface_distance(moved, fixed, samples=samples, seed=seed,
                            band_mm=band_mm)
    return {"pose_index": index,
            "rotation": [[float(v) for v in row] for row in transform[:3, :3]],
            "determinant": round(float(np.linalg.det(transform[:3, :3])), 9),
            "distance": full}


# --------------------------------------------------------------------------
# The hard predicates. Candidate-independent, and frozen before any run.
