def load(path: Path):
    import trimesh
    return trimesh.load(str(path), force="mesh")


def _rings(mesh, z: float) -> list[Any]:
    """The cavity cross-sections at height `z`, as shapely polygons.

    A horizontal slice of a bin is one filled outline with a hole per open
    compartment, so the *interior rings* are the compartments and counting them
    is how divider count is measured without a CAD feature tree. `to_2D` is
    given an explicit transform: its default picks its own planar frame, and a
    frame chosen by the library would make "the divider is on the long axis" a
    statement about whichever basis trimesh happened to return.
    """
    import numpy as np
    from shapely.geometry import Polygon

    section = mesh.section(plane_origin=[0.0, 0.0, z], plane_normal=[0, 0, 1])
    if section is None:
        return []
    world_to_plane = np.eye(4)
    world_to_plane[2, 3] = -z
    flat, _ = section.to_2D(to_2D=world_to_plane)
    return [Polygon(interior) for shape in flat.polygons_full
            for interior in shape.interiors]


def _outer_area(mesh, z: float) -> float:
    import numpy as np
    from shapely.geometry import Polygon

    section = mesh.section(plane_origin=[0.0, 0.0, z], plane_normal=[0, 0, 1])
    if section is None:
        return 0.0
    world_to_plane = np.eye(4)
    world_to_plane[2, 3] = -z
    flat, _ = section.to_2D(to_2D=world_to_plane)
    return float(sum(Polygon(shape.exterior).area
                     for shape in flat.polygons_full))


def _band(low: float, high: float, step: float) -> list[float]:
    """Sample heights, inclusive of both ends and deterministic.

    Deterministic because the prismatic and lip predicates are *comparisons
    between heights*: a sample set that moved between runs would make a passing
    candidate fail on the next invocation for no reason a reader could find.
    """
    if high < low:
        return []
    count = max(1, int(round((high - low) / step)))
    return [low + (high - low) * i / count for i in range(count + 1)]


def features(mesh, geometry: dict[str, Any]) -> dict[str, Any]:
    """Everything the F1 predicates read, measured once off one solid.

    Bands are placed relative to the candidate's **own** top rather than at
    absolute heights, because a candidate that got the height wrong should fail
    the height predicate and still have its divider and its lip measured -- a
    band pinned to the reference's 24.8 mm would report a short bin as having no
    compartments, which blames the wrong thing.
    """
    low, high = mesh.bounds[0], mesh.bounds[1]
    z0, top = float(low[2]), float(high[2])
    height = top - z0
    step = geometry["section_step_mm"]

    base = geometry["base_band"]
    base_zs = _band(z0 + base["low_mm"], z0 + base["high_mm"], step)
    base_rings = [len(_rings(mesh, z)) for z in base_zs]

    comp = geometry["compartment_band"]
    comp_zs = _band(z0 + comp["above_floor_mm"], top - comp["below_top_mm"], step)
    comp_rings = [_rings(mesh, z) for z in comp_zs]
    comp_counts = [len(r) for r in comp_rings]
    comp_areas = [float(sum(p.area for p in r)) for r in comp_rings]
    comp_inner = [_inner_box(r) for r in comp_rings]
    comp_outer = [_outer_area(mesh, z) for z in comp_zs]

    lip = geometry["lip_band"]
    lip_zs = _band(top - lip["below_top_low_mm"], top - lip["below_top_high_mm"],
                   step)
    lip_inner = [_inner_box(_rings(mesh, z)) for z in lip_zs]
    lip_outer = [_outer_area(mesh, z) for z in lip_zs]

    return {
        "height_mm": height,
        "extents_mm": [float(v) for v in mesh.extents],
        "volume_mm3": float(mesh.volume),
        "bodies": int(mesh.body_count),
        "watertight": bool(mesh.is_watertight),
        "base_band_z": base_zs, "base_ring_counts": base_rings,
        "compartment_band_z": comp_zs,
        "compartment_ring_counts": comp_counts,
        "compartment_cavity_area_mm2": comp_areas,
        "compartment_inner_box_mm": comp_inner,
        "compartment_outer_area_mm2": comp_outer,
        "lip_band_z": lip_zs,
        "lip_inner_box_mm": lip_inner,
        "lip_outer_area_mm2": lip_outer,
        "split": _split(comp_rings),
    }


def _inner_box(rings: list[Any]) -> list[float]:
    """The overall opening at one height: the union bbox of every cavity.

    Union rather than per-cavity, so a divider -- which sits *inside* the
    opening -- does not change it. That is what lets the lip predicate compare
    a height with two compartments against a height with one.
    """
    if not rings:
        return [0.0, 0.0]
    xs = [v for ring in rings for v in (ring.bounds[0], ring.bounds[2])]
    ys = [v for ring in rings for v in (ring.bounds[1], ring.bounds[3])]
    return [max(xs) - min(xs), max(ys) - min(ys)]


def _split(bands: list[list[Any]]) -> dict[str, Any] | None:
    """Which axis the compartments are divided along, from their footprints.

    Decided by *disjointness*, not by comparing centroids. Two compartments
    either side of an x-normal divider have disjoint x ranges and identical y
    ranges; centroids alone say the same thing far more weakly, because a pair
    of L-shaped cavities can have separated centroids on an axis neither of them
    is divided along.
    """
    two = [rings for rings in bands if len(rings) == 2]
    if not two:
        return None
    rings = two[len(two) // 2]
    a, b = sorted(rings, key=lambda r: r.bounds[0] + r.bounds[1])
    gap_x = b.bounds[0] - a.bounds[2]
    gap_y = b.bounds[1] - a.bounds[3]
    return {"gap_x_mm": float(gap_x), "gap_y_mm": float(gap_y),
            "axis": "x" if gap_x > gap_y else "y"}


