class E2EError(RuntimeError):
    """The fixture cannot be run as asked. Never a low score."""


class ReferenceUnavailable(corpus.CorpusUnavailable):
    """The hidden reference is not on this machine.

    Subclasses `corpus.CorpusUnavailable` rather than repeating it, so a caller
    that already handles a missing corpus handles a missing E2E reference by the
    same clause. `corpus.resolve` itself does not fit: it addresses a *fetched
    git source*, and this reference is generated by a pinned third-party
    generator into the project tree. What transfers is the discipline -- the
    digest is checked on every call, and absence is loud rather than a skip.
    """


class ReferenceCorrupt(corpus.CorpusCorrupt):
    """The reference is present and is not the bytes the fixture names."""


class RequestLeak(corpus.CorpusLeak):
    """The request package states one of the reference's own measurements."""


