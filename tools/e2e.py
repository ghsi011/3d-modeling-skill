def _row(name: str, ok: bool | None, got: Any, want: str, why: str = ""
         ) -> dict[str, Any]:
    return {"predicate": name, "passes": ok, "measured": got,
            "required": want, "why": why}


def predicates(got: dict[str, Any], geometry: dict[str, Any]
               ) -> list[dict[str, Any]]:
    """Every hard predicate that reads the candidate alone.

    Split from the reference comparison because they answer different
    questions and fail for different reasons. These say *is this the thing the
    brief asked for*; the comparison says *is it the same solid*. A fixture
    that reported one number for both would hide which.
    """
    pitch = geometry["grid_pitch_mm"]
    gap = geometry["grid_gap_mm"]
    tol = geometry["published_tolerance_mm"]
    units_x, units_y = geometry["footprint_units"]
    extents = sorted(got["extents_mm"], reverse=True)

    def footprint(units: int) -> float:
        """The published footprint of a bin `units` cells across.

        `units * pitch - gap`, both numbers published and both stated in the
        request. At revision 1 this was a band on the *undersize* instead, and
        the reason it could not stay is the reviewer's ruling: the brief
        withheld the family's own 0.5 mm gap, so the predicate had to accept
        anything between 0.1 and 1.0 mm under the cell to avoid encoding a
        number the request did not give. The request gives it now, so the
        requirement is the figure and not a range around it.
        """
        return units * pitch - gap

    rows = [
        _row("one_printable_body", got["bodies"] == 1, got["bodies"], "1",
             "an extra solid in the STL is an extra thing on the plate"),
        _row("watertight", got["watertight"], got["watertight"], "True",
             "an open surface has no volume and no defensible moments"),
        _row("footprint_long_mm",
             abs(extents[0] - footprint(units_x)) <= tol,
             round(extents[0], 3),
             f"{footprint(units_x):g} +/- {tol} mm",
             "the published footprint: a cell is the pitch and a bin is the "
             "published widest section, which the request states"),
        _row("footprint_short_mm",
             abs(extents[1] - footprint(units_y)) <= tol,
             round(extents[1], 3),
             f"{footprint(units_y):g} +/- {tol} mm",
             "the published footprint: a cell is the pitch and a bin is the "
             "published widest section, which the request states"),
        _row("height_mm",
             geometry["height_min_mm"] <= got["height_mm"] <= geometry["height_max_mm"],
             round(got["height_mm"], 3),
             f"{geometry['height_min_mm']}..{geometry['height_max_mm']}",
             "the nominal body is the height units times the height unit, and "
             "the lip stands above it. The band spans the lip's published land "
             "at the bottom and the whole published lip at the top, because the "
             "final chamfer cannot be built in full at this wall thickness and "
             "the publication does not say how far to truncate it"),
    ]

    plug = got["base_profile"]
    rows.append(_row(
        "base_plug_profile_mm",
        plug["worst_mm"] is not None and plug["missing_sections"] == 0
        and plug["worst_mm"] <= tol,
        plug["worst_mm"], f"<= {tol} mm from the published profile",
        "the published base profile is what makes the bin interchangeable with "
        "the ones already in the drawer: it is the surface that locates in the "
        "baseplate and the surface the next bin up seats on. The request states "
        "all three segments, so this is a stated dimension held to a stated "
        "tolerance and not a similarity band"))

    radius = got["outer_corner_radius_mm"]
    rows.append(_row(
        "outer_corner_radius_mm",
        radius is not None
        and abs(radius - geometry["outer_corner_radius_mm"]) <= tol,
        None if radius is None else round(radius, 4),
        f"{geometry['outer_corner_radius_mm']} +/- {tol} mm",
        "the corner radius at the widest section is published, and a bin whose "
        "corners are rounder or squarer than the socket does not drop into a "
        "cell the way the family's do"))

    floor = got["floor_top_mm"]
    rows.append(_row(
        "compartment_floor_height_mm",
        floor is not None
        and abs(floor - geometry["base_height_mm"]) <= tol,
        None if floor is None else round(floor, 4),
        f"{geometry['base_height_mm']} +/- {tol} mm",
        "the published base occupies the first height unit including the "
        "structure that ties the feet together, so the top of that structure is "
        "the compartment floor. A floor lower than that is a bin with a hollow "
        "inside its own base"))

    counts = set(got["compartment_ring_counts"])
    want_compartments = geometry["expected_compartments"]
    rows.append(_row(
        "compartment_count", counts == {want_compartments},
        sorted(counts), f"{{{want_compartments}}} at every sampled height",
        "one divider makes two compartments, and it has to be two at every "
        "height in the band -- a divider that stops half way up is a divider "
        "at one sample and not at the next"))

    split = got["split"]
    rows.append(_row(
        "divider_on_long_axis", bool(split) and split["axis"] == geometry["split_axis"],
        split, f"axis {geometry['split_axis']}",
        "the brief asks for the long direction to be split; a divider on the "
        "short axis is one divider in the wrong place, which every count "
        "predicate above would accept"))

    base_bores = max(got["base_ring_counts"], default=0)
    rows.append(_row(
        "no_bores_in_base", base_bores == 0, base_bores, "0",
        "magnet pockets and screw holes are the only reason a closed base "
        "section has a hole in it, and the brief forbids both"))

    feet = set(got["base_feet_counts"])
    want_feet = units_x * units_y
    rows.append(_row(
        "base_feet", feet == {want_feet}, sorted(feet),
        f"{{{want_feet}}} at every sampled height in the base band",
        "the published base profile is stated per grid unit, with the "
        "published gap kept between units so a bin fits a normal grid in any "
        "position. A bin two cells long therefore stands on two feet, and one "
        "plinth spanning both has the same bounding box at every height -- "
        "which is why no profile or footprint row can see the difference and "
        "this one is separate"))

    areas = got["compartment_cavity_area_mm2"]
    if areas:
        spread = (max(areas) - min(areas)) / max(areas)
    else:
        spread = 1.0
    rows.append(_row(
        "compartment_is_prismatic",
        bool(areas) and spread <= geometry["prismatic_tolerance_fraction"],
        round(spread, 5), f"<= {geometry['prismatic_tolerance_fraction']}",
        "a finger scoop is a ramp at the bottom of a compartment and a label "
        "flange is a tab at the top; both are forbidden and both show up as "
        "the open area changing with height, which a straight-walled "
        "compartment does not"))

    inner = got["compartment_inner_box_mm"]
    lip_inner = got["lip_inner_box_mm"]
    if inner and lip_inner:
        comp_x = max(box[0] for box in inner)
        comp_y = max(box[1] for box in inner)
        top_x = min(box[0] for box in lip_inner)
        top_y = min(box[1] for box in lip_inner)
        inset = min((comp_x - top_x) / 2.0, (comp_y - top_y) / 2.0)
    else:
        inset = 0.0
    rows.append(_row(
        "stack_lip_present", inset >= geometry["min_lip_inset_mm"],
        round(inset, 4), f">= {geometry['min_lip_inset_mm']} mm per side",
        "a stacking lip is a ledge that protrudes inward at the top so the "
        "base of the next bin lands on it, so the opening near the top is "
        "narrower than the compartment below it"))

    throat = got["lip_throat"]
    lip = geometry["lip_profile"]
    rows.append(_row(
        "stack_lip_depth_mm",
        throat is not None
        and abs(throat["inset_from_outer_mm"] - lip["depth_mm"]) <= tol,
        None if throat is None else round(throat["inset_from_outer_mm"], 4),
        f"{lip['depth_mm']} +/- {tol} mm from the outer surface",
        "the published lip depth, wall included. This is the surface the next "
        "bin's foot actually seats against, so it is the one number in the lip "
        "that decides whether a stack stands up -- and `stack_lip_present` "
        "above cannot see it, because that row measures the ledge against the "
        "compartment and this one measures it against the grid"))

    seat = geometry["height_units"] * geometry["height_unit_mm"]
    rows.append(_row(
        "stack_lip_seat_height_mm",
        throat is not None and abs(throat["seat_top_mm"] - seat) <= tol,
        None if throat is None else round(throat["seat_top_mm"], 4),
        f"{seat:g} +/- {tol} mm",
        "the lip's inner tip stands at the bin's nominal height, because the "
        "published height unit excludes the lip. A lip in the right shape at "
        "the wrong height is a bin that stacks to the wrong pitch, and every "
        "other lip row here accepts it"))
    return rows


def outer_profile_drift(got: dict[str, Any]) -> float | None:
    """How much the outer cross-section grows between the wall and the rim.

    A **diagnostic**, and it started as a hard predicate. It was demoted for the
    reason section 12 of the brief gives: every predicate that can decide
    PASS/FAIL must have a mutation that proves it can fail, and this one has no
    failure of its own. A rim that flares outward grows the bounding box, so
    `footprint_long_mm` and `footprint_short_mm` already refuse it; a rim that
    grows the cross-section *without* growing the bounding box -- filling the
    corner radii, say -- is 0.35% on this footprint and is not a
    grid-compatibility failure at all. A gate nothing can fail reads exactly
    like one that holds, so it is reported and not gated.
    """
    comp = got["compartment_outer_area_mm2"]
    lip = got["lip_outer_area_mm2"]
    if not comp or not lip:
        return None
    return round(abs(max(lip) - max(comp)) / max(comp), 6)


def distance_mask(geometry: dict[str, Any]) -> dict[str, float]:
    """The two z ranges the hard distance declines to judge, from the request.

    Every bound is arithmetic on numbers the request states, which is the whole
    of the reviewer's condition: a surface judged by reference distance must be
    determined by request-side facts, and one that is not is masked rather than
    made to match hidden geometry. Nothing here is measured off the reference.
    """
    lip = geometry["lip_profile"]
    floor = geometry["base_height_mm"]
    return {
        "tie_low_mm": geometry["base_profile"]["rise_mm"],
        "tie_high_mm": floor,
        "floor_low_mm": floor,
        "floor_high_mm": floor + geometry["internal_fillet_allowance_mm"],
        "lip_land_top_mm": (geometry["height_units"] * geometry["height_unit_mm"]
                            + lip["lower_chamfer_mm"] + lip["land_mm"]),
    }


def corner_radius_probe(geometry: dict[str, Any]) -> float:
    """The height at which the outer section is a section of the published wall.

    Above the base, because that is the first height at which the publication
    fixes what the outline is: the base owns the first height unit and the feet
    finish tying into the body somewhere inside it, at a height the publication
    does not give. Revision 2 probed at 6.0 -- reasoning only that it was above
    the base profile and below the floor -- and 6.0 is inside that span. Run 02
    priced the mistake: a candidate whose corner radius is exactly the published
    3.75 mm everywhere from 6.9 mm upward read 6.77 at 6.0, because at 6.0 its
    section was still a foot growing into a body, and it failed a row it
    satisfies.
    """
    return geometry["base_height_mm"] + geometry["corner_radius_probe_above_base_mm"]


def comparison_rows(registration: dict[str, Any], geometry: dict[str, Any]
                    ) -> list[dict[str, Any]]:
    band = geometry["reference_comparison"]
    distance = registration["distance"]
    mask = distance_mask(geometry)
    return [
        _row("registration_is_a_proper_rotation",
             registration["determinant"] == 1.0, registration["determinant"],
             "det(R) = +1",
             "translation to a named datum and a proper rotation only. No "
             "scaling and no reflection is available to the fitter, so a "
             "mirrored candidate is scored as the mismatch it is"),
        _row("reference_surface_distance_p99_mm",
             distance["p99_mm"] <= band["band_mm"],
             round(distance["p99_mm"], 4), f"<= {band['band_mm']} mm",
             "the determined surfaces only: everything except the tie between "
             f"the feet and the body ({mask['tie_low_mm']:g}.."
             f"{mask['tie_high_mm']:g} mm above the base), the internal floor "
             f"transition ({mask['floor_low_mm']:g}..{mask['floor_high_mm']:g}) "
             f"and everything above the lip's published land "
             f"({mask['lip_land_top_mm']:g}). Band calibrated from "
             "same-geometry noise; see the fixture's calibration block for the "
             "method and what it cannot catch"),
    ]


