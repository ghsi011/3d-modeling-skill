def load(path: Path):
    import trimesh
    return trimesh.load(str(path), force="mesh")


def _rings(mesh, z: float) -> list[Any]:
    """The cavity cross-sections at height `z`, as shapely polygons.

    A horizontal slice of a bin is one filled outline with a hole per open
    compartment, so the *interior rings* are the compartments and counting them
    is how divider count is measured without a CAD feature tree. `to_2D` is
    given an explicit transform: its default picks its own planar frame, and a
    frame chosen by the library would make "the divider is on the long axis" a
    statement about whichever basis trimesh happened to return.
    """
    import numpy as np
    from shapely.geometry import Polygon

    section = mesh.section(plane_origin=[0.0, 0.0, z], plane_normal=[0, 0, 1])
    if section is None:
        return []
    world_to_plane = np.eye(4)
    world_to_plane[2, 3] = -z
    flat, _ = section.to_2D(to_2D=world_to_plane)
    return [Polygon(interior) for shape in flat.polygons_full
            for interior in shape.interiors]


def _outer(mesh, z: float) -> dict[str, float] | None:
    """The solid's own outline at height `z`: its span in x and y, and its area.

    The span is the bounding box of the *exterior* rings, so it is unaffected by
    what is hollowed out of them -- which is what makes it the right instrument
    for the base plug, whose published profile is stated as an inset from the
    footprint and not as an area.
    """
    import numpy as np
    from shapely.geometry import Polygon

    section = mesh.section(plane_origin=[0.0, 0.0, z], plane_normal=[0, 0, 1])
    if section is None:
        return None
    world_to_plane = np.eye(4)
    world_to_plane[2, 3] = -z
    flat, _ = section.to_2D(to_2D=world_to_plane)
    rings = [Polygon(shape.exterior) for shape in flat.polygons_full]
    if not rings:
        return None
    xs = [v for ring in rings for v in (ring.bounds[0], ring.bounds[2])]
    ys = [v for ring in rings for v in (ring.bounds[1], ring.bounds[3])]
    return {"x": max(xs) - min(xs), "y": max(ys) - min(ys),
            "area": float(sum(ring.area for ring in rings))}


def _outer_area(mesh, z: float) -> float:
    got = _outer(mesh, z)
    return 0.0 if got is None else got["area"]


def _outline_count(mesh, z: float) -> int:
    """How many separate solids the section at `z` cuts through.

    One per foot down in the base, and one for the whole bin above it. The
    published base profile is stated per grid unit with a gap between units, so
    a bin two cells long stands on two feet and this is what says so -- and it
    is the only row that can, because two feet on the pitch and one plinth
    spanning them have the same bounding box at every height.
    """
    import numpy as np

    section = mesh.section(plane_origin=[0.0, 0.0, z], plane_normal=[0, 0, 1])
    if section is None:
        return 0
    world_to_plane = np.eye(4)
    world_to_plane[2, 3] = -z
    flat, _ = section.to_2D(to_2D=world_to_plane)
    return len(flat.polygons_full)


def _corner_radius(mesh, z: float) -> float | None:
    """The outline's corner radius at height `z`, from its area deficit.

    A rounded rectangle of span `w` x `h` and radius `r` is short of its own
    bounding box by exactly `(4 - pi) r^2`, one quarter-square-minus-quarter-
    disc per corner, so the radius follows from three numbers the section
    already carries. Measured rather than fitted because a fitter needs to be
    told which vertices are the arc, and the answer would then depend on the
    tessellation that produced them.

    Corroborated by a second method on the reference at ingest -- the shortest
    distance from a bounding-box corner to the outline, which is `r (sqrt2 - 1)`
    -- and the two agree to 0.003 mm (3.7528 against 3.7500 for a published
    3.75). The fixture records both; only one of them is cheap enough to run on
    every candidate, and it is this one.
    """
    import math

    got = _outer(mesh, z)
    if got is None or got["x"] <= 0 or got["y"] <= 0:
        return None
    deficit = got["x"] * got["y"] - got["area"]
    if deficit <= 0:
        return 0.0
    return math.sqrt(deficit / (4.0 - math.pi))


def _band(low: float, high: float, step: float) -> list[float]:
    """Sample heights, inclusive of both ends and deterministic.

    Deterministic because the prismatic and lip predicates are *comparisons
    between heights*: a sample set that moved between runs would make a passing
    candidate fail on the next invocation for no reason a reader could find.
    """
    if high < low:
        return []
    count = max(1, int(round((high - low) / step)))
    return [low + (high - low) * i / count for i in range(count + 1)]


def _floor_top(mesh, z0: float, top: float, step: float) -> float | None:
    """The height at which the compartments open: the top face of the floor.

    Found by scanning up from the base for the first section with an interior
    ring and then bisecting, rather than by reading a chosen height. The
    published interface fixes this number -- the base occupies the first height
    unit -- so it is a thing to measure on a candidate, not a thing to assume
    about one.
    """
    found = None
    z = z0 + step
    while z < top:
        if _rings(mesh, z):
            found = z
            break
        z += step
    if found is None:
        return None
    low, high = found - step, found
    for _ in range(8):                        # to about 0.002 mm at step 0.5
        middle = (low + high) / 2.0
        if _rings(mesh, middle):
            high = middle
        else:
            low = middle
    return high - z0


def _lip_throat(mesh, z0: float, top: float, scan_mm: float, step: float,
                flat_mm: float) -> dict[str, float] | None:
    """The narrowest opening near the rim, and how far up it reaches.

    The stacking lip is a ledge that hangs into the bin, so the opening has a
    minimum -- the throat -- with the lip's underside ramp below it and the
    socket the next bin's base drops into above it. Two numbers come out and the
    published profile fixes both: how far the throat is inset from the outer
    surface (the lip's stated depth, wall included), and the height of the top
    of the throat (the profile's inner tip, which sits at the bin's nominal
    height).

    `flat_mm` is the tolerance for "still the throat": the throat is a straight
    section of finite height, and a tessellated section of it wanders by a few
    microns. It is not an acceptance band -- the acceptance bands are applied by
    the predicates, against the published numbers.
    """
    scan = []
    z = max(z0, top - scan_mm)
    while z <= top - 1e-9:
        rings = _rings(mesh, z)
        outer = _outer(mesh, z)
        if rings and outer:
            box = _inner_box(rings)
            scan.append((z, box[0], box[1], outer["x"]))
        z += step
    if not scan:
        return None
    narrowest = min(row[1] for row in scan)
    at = [row for row in scan if row[1] <= narrowest + flat_mm]
    seat = max(row[0] for row in at)
    outer_there = next(row[3] for row in at if row[0] == seat)
    return {"opening_mm": narrowest,
            "inset_from_outer_mm": (outer_there - narrowest) / 2.0,
            "seat_top_mm": seat - z0}


def base_profile_deviation(mesh, z0: float, geometry: dict[str, Any]
                           ) -> dict[str, Any]:
    """How far the candidate's plug is from the published base profile.

    The published profile is three segments read from the bottom of the foot --
    a 45 degree chamfer, a straight land, a second 45 degree chamfer -- and it
    is stated in the request, so this compares a measured outline against a
    *request-side* number and not against the reference. Sampled a stated margin
    inside each segment, because a section taken exactly on a segment boundary
    is a section of an edge, and which side of it a tessellation lands on is not
    a property of the design.
    """
    plug = geometry["base_profile"]
    lower, land, upper = (plug["lower_chamfer_mm"], plug["land_mm"],
                          plug["upper_chamfer_mm"])
    run = plug["run_mm"]
    margin = plug["sample_margin_mm"]
    pitch = geometry["grid_pitch_mm"]
    gap = geometry["grid_gap_mm"]
    units_x, units_y = geometry["footprint_units"]
    full_x = units_x * pitch - gap
    full_y = units_y * pitch - gap

    def inset(z: float) -> float:
        """The published inset from the footprint at height `z` up the foot."""
        if z <= lower:
            return run - z
        if z <= lower + land:
            return upper
        return max(0.0, upper - (z - lower - land))

    heights = []
    for low, high in ((0.0, lower), (lower, lower + land),
                      (lower + land, lower + land + upper)):
        heights += [low + margin, (low + high) / 2.0, high - margin]

    rows = []
    for z in heights:
        got = _outer(mesh, z0 + z)
        if got is None:
            rows.append({"z_mm": round(z, 4), "measured_x_mm": None,
                         "measured_y_mm": None, "deviation_mm": None})
            continue
        want_x, want_y = full_x - 2 * inset(z), full_y - 2 * inset(z)
        rows.append({
            "z_mm": round(z, 4),
            "measured_x_mm": round(got["x"], 4),
            "measured_y_mm": round(got["y"], 4),
            "required_x_mm": round(want_x, 4),
            "required_y_mm": round(want_y, 4),
            "deviation_mm": round(max(abs(got["x"] - want_x),
                                      abs(got["y"] - want_y)), 4)})
    seen = [row["deviation_mm"] for row in rows if row["deviation_mm"] is not None]
    return {"samples": rows,
            "worst_mm": max(seen) if seen else None,
            "missing_sections": len(rows) - len(seen)}


def features(mesh, geometry: dict[str, Any]) -> dict[str, Any]:
    """Everything the F1 predicates read, measured once off one solid.

    Bands are placed relative to the candidate's **own** top rather than at
    absolute heights, because a candidate that got the height wrong should fail
    the height predicate and still have its divider and its lip measured -- a
    band pinned to the reference's 24.8 mm would report a short bin as having no
    compartments, which blames the wrong thing.

    The revision-2 rows are the other way round on purpose. The base plug, the
    floor height, the corner radius and the lip throat are measured from the
    candidate's own base plane against numbers the *request* states, so they are
    absolute: a bin whose foot is 0.25 mm too tall has built the published
    profile wrongly, and a band that floated with it would say so about nothing.
    """
    low, high = mesh.bounds[0], mesh.bounds[1]
    z0, top = float(low[2]), float(high[2])
    height = top - z0
    step = geometry["section_step_mm"]

    base = geometry["base_band"]
    base_zs = _band(z0 + base["low_mm"], z0 + base["high_mm"], step)
    base_rings = [len(_rings(mesh, z)) for z in base_zs]
    base_feet = [_outline_count(mesh, z) for z in base_zs]

    comp = geometry["compartment_band"]
    comp_zs = _band(z0 + comp["low_mm"], z0 + comp["high_mm"], step)
    comp_rings = [_rings(mesh, z) for z in comp_zs]
    comp_counts = [len(r) for r in comp_rings]
    comp_areas = [float(sum(p.area for p in r)) for r in comp_rings]
    comp_inner = [_inner_box(r) for r in comp_rings]
    comp_outer = [_outer_area(mesh, z) for z in comp_zs]

    lip = geometry["lip_band"]
    lip_zs = _band(top - lip["below_top_low_mm"], top - lip["below_top_high_mm"],
                   step)
    lip_inner = [_inner_box(_rings(mesh, z)) for z in lip_zs]
    lip_outer = [_outer_area(mesh, z) for z in lip_zs]

    lip_scan = geometry["lip_throat"]
    throat = _lip_throat(mesh, z0, top, lip_scan["scan_mm"],
                         lip_scan["step_mm"], lip_scan["flat_tolerance_mm"])

    return {
        "height_mm": height,
        "extents_mm": [float(v) for v in mesh.extents],
        "volume_mm3": float(mesh.volume),
        "bodies": int(mesh.body_count),
        "watertight": bool(mesh.is_watertight),
        "base_feet_counts": base_feet,
        "base_profile": base_profile_deviation(mesh, z0, geometry),
        "outer_corner_radius_mm": _corner_radius(
            mesh, z0 + corner_radius_probe(geometry)),
        "floor_top_mm": _floor_top(mesh, z0, top, step),
        "lip_throat": throat,
        "base_band_z": base_zs, "base_ring_counts": base_rings,
        "compartment_band_z": comp_zs,
        "compartment_ring_counts": comp_counts,
        "compartment_cavity_area_mm2": comp_areas,
        "compartment_inner_box_mm": comp_inner,
        "compartment_outer_area_mm2": comp_outer,
        "lip_band_z": lip_zs,
        "lip_inner_box_mm": lip_inner,
        "lip_outer_area_mm2": lip_outer,
        "split": _split(comp_rings),
    }


def _inner_box(rings: list[Any]) -> list[float]:
    """The overall opening at one height: the union bbox of every cavity.

    Union rather than per-cavity, so a divider -- which sits *inside* the
    opening -- does not change it. That is what lets the lip predicate compare
    a height with two compartments against a height with one.
    """
    if not rings:
        return [0.0, 0.0]
    xs = [v for ring in rings for v in (ring.bounds[0], ring.bounds[2])]
    ys = [v for ring in rings for v in (ring.bounds[1], ring.bounds[3])]
    return [max(xs) - min(xs), max(ys) - min(ys)]


def _split(bands: list[list[Any]]) -> dict[str, Any] | None:
    """Which axis the compartments are divided along, from their footprints.

    Decided by *disjointness*, not by comparing centroids. Two compartments
    either side of an x-normal divider have disjoint x ranges and identical y
    ranges; centroids alone say the same thing far more weakly, because a pair
    of L-shaped cavities can have separated centroids on an axis neither of them
    is divided along.
    """
    two = [rings for rings in bands if len(rings) == 2]
    if not two:
        return None
    rings = two[len(two) // 2]
    a, b = sorted(rings, key=lambda r: r.bounds[0] + r.bounds[1])
    gap_x = b.bounds[0] - a.bounds[2]
    gap_y = b.bounds[1] - a.bounds[3]
    return {"gap_x_mm": float(gap_x), "gap_y_mm": float(gap_y),
            "axis": "x" if gap_x > gap_y else "y"}


