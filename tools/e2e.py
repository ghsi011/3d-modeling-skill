def score(candidate_stl: Path, three_mf: Path | None = None,
          spec: dict[str, Any] | None = None, *,
          request_dir: Path | None = None,
          design_path_seconds: float | None = None,
          authoring_root: str | None = None) -> dict[str, Any]:
    """Every hard predicate and every diagnostic, with the clock split in two.

    `PASS` is the conjunction of the hard predicates and never a weighted
    total, per brief section 10. `timings` reports the harness apart from the
    design path because the reviewer asked for them apart: a blended number
    cannot answer *is the benchmark expensive or is CAD expensive*, and those
    have different remedies.
    """
    clock: dict[str, float] = {}

    def timed(name: str, work):
        start = time.perf_counter()
        out = work()
        clock[name] = round(time.perf_counter() - start, 4)
        return out

    spec = spec or fixture()
    geometry = spec["geometry"]
    candidate_stl = Path(candidate_stl)
    if not candidate_stl.is_file():
        raise E2EError(f"no candidate at {candidate_stl}")

    reference = timed("resolve_reference", lambda: reference_path(spec))
    ref_mesh = timed("load_reference", lambda: load(reference))
    measured = timed("measure_reference", lambda: {
        "extent_x": float(ref_mesh.extents[0]),
        "extent_y": float(ref_mesh.extents[1]),
        "extent_z": float(ref_mesh.extents[2]),
        "volume_mm3": float(ref_mesh.volume)})

    leak = timed("audit_request",
                 lambda: audit_request(spec, request_dir, measured)
                 if request_dir else None)

    mesh = timed("load_candidate", lambda: load(candidate_stl))
    got = timed("measure_candidate", lambda: features(mesh, geometry))
    hard = timed("predicates", lambda: predicates(got, geometry))
    registration = timed("registration", lambda: register(
        mesh, ref_mesh,
        samples=geometry["reference_comparison"]["samples"],
        seed=geometry["reference_comparison"]["seed"],
        band_mm=geometry["reference_comparison"]["band_mm"]))
    hard += timed("comparison", lambda: comparison_rows(registration, geometry))
    mf = timed("three_mf", lambda: three_mf_rows(three_mf, mesh, geometry)
               if three_mf else [])

    cad_pass = all(row["passes"] for row in hard)
    mf_pass = all(row["passes"] for row in mf) if mf else None
    return {
        "schema_version": 1,
        "fixture": spec["id"],
        "fixture_revision": spec["revision"],
        "scorer": "tools/e2e.py",
        "scorer_commit": scorer_commit(),
        "candidate_stl_sha256": _digest(candidate_stl),
        "three_mf_sha256": _digest(Path(three_mf)) if three_mf and
        Path(three_mf).is_file() else None,
        "reference_sha256": spec["reference"]["sha256"],
        "verdict": ("CAD_PASS" if cad_pass else "CAD_FAIL") +
                   ("" if mf_pass is None else
                    (" / 3MF_PASS" if mf_pass else " / 3MF_FAIL")),
        "hard_predicates": hard,
        "three_mf": mf,
        "diagnostics": {
            "sorted_extents_mm": sorted(got["extents_mm"]),
            "volume_mm3": got["volume_mm3"],
            "reference_volume_mm3": measured["volume_mm3"],
            "surface_distance": registration["distance"],
            "pose_index": registration["pose_index"],
            "compartment_inner_box_mm": got["compartment_inner_box_mm"][:1],
            "cavity_area_mm2": got["compartment_cavity_area_mm2"][:1],
            "outer_profile_drift": outer_profile_drift(got),
            # NOT the interior usable volume, which is what this was first
            # called. It is the open area integrated over `compartment_band`
            # only -- the floor fillet below it and the lip region above it are
            # outside the band -- so it understates the usable volume by
            # whatever those contribute. Renamed rather than corrected because
            # the band is what the prismatic predicate reads, and a diagnostic
            # that reports the quantity a predicate actually saw is worth more
            # than one that reports a different quantity under a better name.
            "cavity_area_integrated_over_band_mm3": round(
                sum(got["compartment_cavity_area_mm2"]) *
                geometry["section_step_mm"], 3),
        },
        "request_audit": leak,
        "authoring_root": authoring_root,
        "timings": {
            "harness_seconds": round(sum(clock.values()), 3),
            "harness_breakdown_seconds": clock,
            "design_path_seconds": design_path_seconds,
            "note": "the two are never summed. The harness number is this "
                    "module; the design path is the authoring turn plus "
                    "design-tool run, measured by the caller.",
        },
    }


def render(report: dict[str, Any]) -> str:
    lines = [f"# {report['fixture']} — {report['verdict']}", "",
             f"* fixture revision `{report['fixture_revision']}`",
             f"* candidate `{report['candidate_stl_sha256'][:12]}`",
             f"* reference `{report['reference_sha256'][:12]}`", "",
             "## Hard predicates", "",
             "| predicate | verdict | measured | required |",
             "| --- | --- | --- | --- |"]
    for row in report["hard_predicates"] + report["three_mf"]:
        mark = {True: "PASS", False: "**FAIL**", None: "--"}[row["passes"]]
        lines.append(f"| `{row['predicate']}` | {mark} | "
                     f"{row['measured']} | {row['required']} |")
    clock = report["timings"]
    lines += ["", "## Cost", "",
              f"* harness {clock['harness_seconds']} s",
              f"* design path {clock['design_path_seconds']} s", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="tools/e2e.py",
        description="F1's live end-to-end arm: write the request, or score "
                    "what the real design path returned.")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--ask", action="store_true")
    group.add_argument("--score", metavar="CANDIDATE_STL", type=Path)
    parser.add_argument("--into", type=Path, default=None)
    parser.add_argument("--three-mf", type=Path, default=None)
    parser.add_argument("--request", type=Path, default=None)
    parser.add_argument("--design-seconds", type=float, default=None)
    parser.add_argument("--authoring-root", default=None)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)

    spec = fixture()
    if args.ask:
        if args.into is None:
            parser.error("--ask needs --into <directory>")
        where = write_request(spec, args.into)
        print(f"\n  wrote {where}\n")
        return 0

    try:
        report = score(args.score, args.three_mf, spec,
                       request_dir=args.request,
                       design_path_seconds=args.design_seconds,
                       authoring_root=args.authoring_root)
    except (E2EError, ReferenceUnavailable, ReferenceCorrupt, RequestLeak) as exc:
        sys.stderr.write(f"e2e: {exc}\n")
        return 2
    if args.out:
        args.out.mkdir(parents=True, exist_ok=True)
        (args.out / "result.json").write_text(
            json.dumps(report, indent=2, sort_keys=True) + "\n",
            encoding="utf-8", newline="\n")
        (args.out / "result.md").write_text(render(report), encoding="utf-8",
                                            newline="\n")
    print(render(report))
    return 0 if report["verdict"].startswith("CAD_PASS") else 1


if __name__ == "__main__":
    raise SystemExit(main())
