def fixture(path: Path | None = None) -> dict[str, Any]:
    return json.loads(Path(path or FIXTURE).read_text(encoding="utf-8"))


def scorer_commit() -> str | None:
    """The commit this scorer is, or None when that cannot be established.

    Brief section 10 requires the run report to bind the scorer's version
    alongside the candidate and reference digests, and it is the one binding a
    report cannot reconstruct later: two runs of the same candidate against the
    same reference can disagree, and without this there is nothing in the
    payload that says which scorer produced which.

    `None` rather than a guess when the tree is dirty or git cannot answer. A
    commit id printed beside uncommitted changes is a stronger claim than the
    evidence supports -- it says "this is the code that ran" about code that is
    not what ran.
    """
    import subprocess

    try:
        head = subprocess.run(["git", "-c", "safe.directory=*", "rev-parse",
                               "HEAD"], cwd=str(ROOT), capture_output=True,
                              text=True, check=False)
        dirty = subprocess.run(["git", "-c", "safe.directory=*", "status",
                                "--porcelain"], cwd=str(ROOT),
                               capture_output=True, text=True, check=False)
    except OSError:
        return None
    if head.returncode != 0 or dirty.returncode != 0:
        return None
    if dirty.stdout.strip():
        return None
    return head.stdout.strip() or None


def _digest(path: Path) -> str:
    reader = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            reader.update(block)
    return reader.hexdigest()


def reference_path(spec: dict[str, Any] | None = None) -> Path:
    """Where the scored reference is, proven to be the bytes the fixture names.

    Verified on every call, not once at ingest. A digest checked when the file
    was generated says nothing about the file this run is about to read, and the
    cost is a hash of a file already in the page cache -- the argument
    `corpus.resolve` makes, and the property that makes a drifted reference a
    loud failure instead of a different answer.
    """
    spec = spec or fixture()
    block = spec["reference"]
    root = Path(os.environ.get(block["root"]["env"], block["root"]["default"]))
    path = (root / block["path"]).expanduser()
    if not path.is_file():
        raise ReferenceUnavailable(
            f"{spec['id']}'s reference is not at {path}. It is generated, not "
            f"fetched: {block['generator']['install']} then "
            f"{block['generator']['call']}, normalised through "
            f"mesh_io.normalize_mesh. Set {block['root']['env']} if it lives "
            "elsewhere.")
    found = _digest(path)
    if found != block["sha256"]:
        raise ReferenceCorrupt(
            f"{spec['id']}'s reference at {path} hashes {found[:12]} and the "
            f"fixture names {block['sha256'][:12]}. A benchmark scored against "
            "a drifted reference produces a number indistinguishable from a "
            "real one.")
    return path


