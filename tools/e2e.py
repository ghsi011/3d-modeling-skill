_CORE_NS = "{http://schemas.microsoft.com/3dmanufacturing/core/2015/02}"


def read_three_mf(path: Path) -> dict[str, Any]:
    """The printable objects a 3MF actually places, read without `lxml`.

    `trimesh.load` cannot open a 3MF in this repository's default install:
    its loader needs `lxml`, which is only in the `bambu` extra, so the reload
    raises `ModuleNotFoundError` on a runtime-only sync. That is
    `docs/defects.md` D3 -- *the round-trip reload check has never executed in
    the frozen runtime* -- reproduced here, and it is why a 3MF gate that
    depended on `trimesh.load` would report the archive unreadable on every
    machine that had not selected an unrelated slicer extra.

    So the archive is read with the standard library. That is also the stricter
    reading: the build items are resolved through their components, so an extra
    body hidden as a second component of the placed assembly is counted, and an
    object that exists in `<resources>` but is never placed is not -- and those
    are two different findings that a concatenating loader merges into one mesh.
    """
    import numpy as np
    import trimesh
    from xml.etree import ElementTree

    with zipfile.ZipFile(path) as archive:
        name = next((n for n in archive.namelist()
                     if n.lower().endswith("3dmodel.model")), None)
        if name is None:
            raise E2EError(f"{path} has no 3D model part")
        root = ElementTree.fromstring(archive.read(name))

    unit = root.get("unit")
    meshes: dict[str, Any] = {}
    components: dict[str, list[tuple[str, Any]]] = {}
    for obj in root.iter(f"{_CORE_NS}object"):
        oid = obj.get("id")
        mesh = obj.find(f"{_CORE_NS}mesh")
        if mesh is not None:
            vertices = np.array(
                [[float(v.get("x")), float(v.get("y")), float(v.get("z"))]
                 for v in mesh.iter(f"{_CORE_NS}vertex")], dtype=float)
            faces = np.array(
                [[int(t.get("v1")), int(t.get("v2")), int(t.get("v3"))]
                 for t in mesh.iter(f"{_CORE_NS}triangle")], dtype=np.int64)
            meshes[oid] = trimesh.Trimesh(vertices=vertices, faces=faces,
                                          process=False)
        group = obj.find(f"{_CORE_NS}components")
        if group is not None:
            components[oid] = [(c.get("objectid"), _matrix(c.get("transform")))
                               for c in group.iter(f"{_CORE_NS}component")]

    placed: list[Any] = []

    def place(oid: str, transform, depth: int = 0) -> None:
        if depth > 8:                       # a components cycle, not a model
            raise E2EError(f"{path}: component nesting does not terminate")
        if oid in meshes:
            body = meshes[oid].copy()
            body.apply_transform(transform)
            placed.append(body)
        for child, child_transform in components.get(oid, ()):
            place(child, transform @ child_transform, depth + 1)

    items = list(root.iter(f"{_CORE_NS}item"))
    for item in items:
        place(item.get("objectid"), _matrix(item.get("transform")))
    return {"unit": unit, "build_items": len(items),
            "printable_bodies": len(placed),
            "resource_meshes": len(meshes), "bodies": placed}


def _matrix(raw: str | None):
    """A 3MF `transform` attribute as a 4x4, or the identity when absent.

    3MF writes the affine as twelve numbers in row-major order for a 4x3
    matrix whose last row is the translation, which is the transpose of what
    trimesh applies. Getting that backwards silently rotates a placed body, so
    it is written out rather than assumed.
    """
    import numpy as np

    out = np.eye(4)
    if not raw:
        return out
    values = [float(v) for v in raw.split()]
    if len(values) != 12:
        raise E2EError(f"a 3MF transform has twelve numbers, not {len(values)}")
    out[:3, :3] = np.array(values[:9], dtype=float).reshape(3, 3).T
    out[:3, 3] = values[9:]
    return out


def three_mf_rows(path: Path, accepted, geometry: dict[str, Any]
                  ) -> list[dict[str, Any]]:
    """3MF is a delivery gate and is reported apart from the CAD verdict.

    Brief section 2.2: no byte comparison, no ZIP metadata, no UUIDs, no object
    ordering. What is checked is that the archive is readable, places the
    printable objects the accepted STL set carries and no others, declares
    millimetres, and holds *this* geometry rather than an earlier export --
    which is the failure a stale 3MF produces and the one a body count cannot
    see.
    """
    path = Path(path) if path else None
    if path is None or not path.is_file():
        return [_row("three_mf_present", False, str(path), "a 3MF file",
                     "the brief requires one and the run did not produce it")]
    rows = [_row("three_mf_present", True, path.name, "a 3MF file", "")]
    try:
        read = read_three_mf(path)
    except (OSError, zipfile.BadZipFile, E2EError, ValueError) as exc:
        return rows + [_row("three_mf_readable", False, f"{type(exc).__name__}: "
                            f"{exc}", "a readable OPC archive", "")]
    rows.append(_row("three_mf_readable", True, "3D/3dmodel.model",
                     "3D/3dmodel.model", ""))
    rows.append(_row("three_mf_unit_is_millimetre", read["unit"] == "millimeter",
                     read["unit"], "millimeter",
                     "3MF's default unit is the micron, so an unstated or "
                     "wrong unit is a thousandfold scale error that no "
                     "geometry check would report as a unit problem"))
    rows.append(_row("three_mf_printable_body_count",
                     read["printable_bodies"] == 1, read["printable_bodies"],
                     "1",
                     "counted through the build items and their components, so "
                     "a second body welded into the placed assembly is a "
                     "finding rather than extra triangles in one mesh"))
    if not read["bodies"]:
        return rows + [_row("three_mf_matches_the_accepted_stl", False, 0,
                            "geometry", "the archive places nothing")]

    import trimesh

    loaded = trimesh.util.concatenate(read["bodies"])
    band = geometry["three_mf"]["band_mm"]
    distance = surface_distance(loaded, accepted,
                                samples=geometry["three_mf"]["samples"],
                                seed=geometry["reference_comparison"]["seed"],
                                band_mm=band)
    rows.append(_row("three_mf_matches_the_accepted_stl",
                     distance["p99_mm"] <= band, round(distance["p99_mm"], 6),
                     f"<= {band} mm",
                     "calibrated from an export/reload of the same geometry, "
                     "so this fails for a stale or substituted body and not "
                     "for the coordinate quantisation every export makes"))
    rows.append(_row("three_mf_volume_delta_mm3", True,
                     round(float(loaded.volume) - float(accepted.volume), 6),
                     "diagnostic", "reported, not gated"))
    return rows


