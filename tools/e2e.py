def write_request(spec: dict[str, Any], into: Path) -> Path:
    """Lay the question down as a directory the real design path can be run in.

    The brief is carried verbatim from the fixture rather than composed here:
    it is the one artifact a designer reads, so it is reviewable as text in the
    diff that freezes it, not as the output of a formatter nobody runs.
    """
    into = Path(into)
    (into / "request").mkdir(parents=True, exist_ok=True)
    brief = "\n".join(spec["request"]["brief"]) + "\n"
    (into / "request" / "brief.md").write_text(brief, encoding="utf-8",
                                               newline="\n")
    (into / "request" / "project.json").write_text(
        json.dumps(spec["request"]["project"], indent=2, sort_keys=True) + "\n",
        encoding="utf-8", newline="\n")
    return into / "request"


def audit_request(spec: dict[str, Any], request_dir: Path,
                  measured: dict[str, float]) -> dict[str, Any]:
    """Refuse a request package that states one of the reference's own numbers.

    `corpus.numbers_in` and `corpus.coincidences`, applied to the bytes a
    designer is actually handed rather than to the manifest that produced them
    -- a rule enforced on the manifest and not on its output is a rule about a
    file nobody reads (`tools/test_blind.py`'s own words).

    One coincidence is *declared* and it is the reason this function returns a
    record instead of only raising. The published grid pitch is 42 mm and a
    one-unit-wide bin is one pitch less the standard clearance, so a requester
    who states the pitch -- which is the only way the request is answerable at
    all -- necessarily states the short footprint to within 1.2%. That is
    `docs/defects.md` D30's shape exactly, and it is declared in the fixture
    with the public source a reader can check. Everything undeclared is refused.
    """
    declared = {row["measurement"] for row in spec["request"].get("discloses", ())}
    text = "\n".join(sorted(p.read_text(encoding="utf-8")
                            for p in sorted(Path(request_dir).rglob("*"))
                            if p.is_file()))
    found = corpus.coincidences(corpus.numbers_in(text), measured)
    undeclared = [pair for pair in found if pair[1] not in declared]
    if undeclared:
        detail = "; ".join(f"{value:g} is the reference's {name}"
                           for value, name in undeclared)
        raise RequestLeak(
            f"{spec['id']}: the request package states a measurement of the "
            f"reference itself -- {detail}. The prohibition covers derived "
            "measurements, not only the mesh: declare it in the fixture with a "
            "public source, or take it out of the brief.")
    # A disclosure that gives away nothing is an exemption with a sentence
    # attached, and it would excuse that axis for every future edit of this
    # fixture -- `corpus.request_view` refuses one for that reason and so does
    # this.
    spurious = sorted(declared - {name for _, name in found})
    if spurious:
        raise RequestLeak(
            f"{spec['id']}: discloses {', '.join(spurious)}, and the request "
            "states no number that measures it.")
    return {"coincidences": [[value, name] for value, name in found],
            "declared": sorted(declared)}


