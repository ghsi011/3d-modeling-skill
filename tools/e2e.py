#!/usr/bin/env python3
"""F1's live end-to-end arm: write the request, gate what the real path returns.

Slice A of `docs/agents/qa-e2e-implementation.md`, and only that: one fixture,
one truth model, no framework. The document's section 13 says so in as many
words -- *do not implement them in one giant abstraction-first PR* -- and its
section 3 is the reason it matters here. F1 is a **reference-determined** design
(section 3.1); F2 is functional with many valid answers and F4 is preservation,
and a shell generalised across the three before any of them has run would be
generalising imagined requirements. So everything below names the grid bin.

**What this module is for.** `tools/blind.py` asks the corpus a question and
scores four dimensional measurements plus one shape descriptor. That is not
enough for F1, and not because the scorer is weak: F1's request is *a
specification*, and the acceptance is *did you build what the standard says* --
divider count, divider axis, lip present, forbidden features absent. Those are
topological facts about a solid and no bounding box can see them.

It is also deliberately **not** routed through `corpus.request_view`.
`tools/corpus.py`'s wall answers one question -- *does this requirement measure
a declared counterpart, or the part itself* -- and it is the right question for a
reconstruct-from-what-it-fits benchmark. F1 states `divider_count` and
`stack_lip`, which measure the part and are exactly what a requester
legitimately asks for, so that rule would refuse a valid request. What is reused
is the half that does transfer, and it is the strongest half:
`corpus.numbers_in` and `corpus.coincidences` audit **this** request against the
reference's own measurements, so a number that leaked into the brief is a hard
failure here for the same reason it is there.

**The requester-side prohibition is structural, not a promise.** The boundary
includes derived measurements, not just the reference mesh: on the bee fixture
the designer voluntarily avoided the measurement scripts, and a harness that
depends on that restraint is measuring the designer's manners. `audit_request`
compares every number in the materialised request package against the
reference's extents and volume and refuses an undeclared coincidence. What it
cannot do is stop a designer reading the reference off the filesystem, so the
run also puts the working directory somewhere with no path to it; the two
together are the boundary, and `score()` records which of them was in force.

**Registration fits translation and a proper rotation, and nothing else.**
Section 4 of the brief: no scaling, no reflection, `det(R) = +1`. The pose set
here is the 24 proper rotations of a cuboid rather than a fitted ICP, because
this fixture's parts are axis-aligned prisms and an unconstrained fitter is
exactly what erases a handedness error. `PROPER_ROTATIONS` is generated by
filtering the 48 signed permutations on determinant, so the improper half is
absent by construction rather than by a comment.

**The translation is a named datum, not a bounding-box centroid.** Section 4.4
of the brief prefers fixture-defined datums before generic fitting, and at
revision 2 this stopped being a preference. The published lip profile cannot be
built in full at a 1.0 mm wall, so two correct bins may legitimately differ in
overall height; a centroid fit spreads half that difference over *every*
surface as a z offset, and the base plug -- which the request now dimensions
exactly -- would be scored against an error it did not make. Both solids are
therefore seated on the plane they print on (`min z -> 0`) and centred on their
own footprint in x and y.

**The hard distance judges only what the request determines.** Revision 2's
whole point: a surface may decide PASS/FAIL by reference distance only where
the published interface in the request fixes it. Two regions on this part fail
that test and are masked out of the distance -- the internal floor transition,
whose fillet the published source does not fix, and everything above the lip's
published land, where the final chamfer has to be truncated by an amount the
publication does not state. Both bounds are computed from request-side numbers
in `benchmarks/e2e/f1-gridbin.json`; the unmasked distribution is still
reported, as a diagnostic.

**Every band is calibrated from same-geometry noise.** Section 5, and the
numbers live in `benchmarks/e2e/f1-gridbin.json` under `calibration` with the
method that produced them. Nothing in this file chooses a tolerance.
"""
