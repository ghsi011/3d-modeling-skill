def _row(name: str, ok: bool | None, got: Any, want: str, why: str = ""
         ) -> dict[str, Any]:
    return {"predicate": name, "passes": ok, "measured": got,
            "required": want, "why": why}


def predicates(got: dict[str, Any], geometry: dict[str, Any]
               ) -> list[dict[str, Any]]:
    """Every hard predicate that reads the candidate alone.

    Split from the reference comparison because they answer different
    questions and fail for different reasons. These say *is this the thing the
    brief asked for*; the comparison says *is it the same solid*. A fixture
    that reported one number for both would hide which.
    """
    pitch = geometry["grid_pitch_mm"]
    least = geometry["footprint_min_undersize_mm"]
    most = geometry["footprint_max_undersize_mm"]
    units_x, units_y = geometry["footprint_units"]
    extents = sorted(got["extents_mm"], reverse=True)

    def drops_into_the_grid(measured: float, units: int) -> bool:
        """Undersize by a working amount, rather than equal to a stated number.

        A cell of `units` pitches is the space available, so a bin that is
        exactly that wide binds and one that is a millimetre under rattles.
        Expressed as a band on the *undersize* because that is what the request
        gives -- the pitch and 'drops in and comes out again'. The alternative,
        `units * pitch - 0.5 +/- tol`, would need the published clearance to be
        exactly right, and it would put the reference's own 41.5 into the
        predicate as a target rather than deriving a requirement from the
        interface.
        """
        under = units * pitch - measured
        return least <= under <= most

    rows = [
        _row("one_printable_body", got["bodies"] == 1, got["bodies"], "1",
             "an extra solid in the STL is an extra thing on the plate"),
        _row("watertight", got["watertight"], got["watertight"], "True",
             "an open surface has no volume and no defensible moments"),
        _row("footprint_long_mm", drops_into_the_grid(extents[0], units_x),
             round(extents[0], 3),
             f"{units_x} x {pitch} mm less {least}..{most} mm",
             "the published pitch and the requirement that the bin drop into a "
             "cell and lift back out; no reference measurement is involved"),
        _row("footprint_short_mm", drops_into_the_grid(extents[1], units_y),
             round(extents[1], 3),
             f"{units_y} x {pitch} mm less {least}..{most} mm",
             "the published pitch and the requirement that the bin drop into a "
             "cell and lift back out; no reference measurement is involved"),
        _row("height_mm",
             geometry["height_min_mm"] <= got["height_mm"] <= geometry["height_max_mm"],
             round(got["height_mm"], 3),
             f"{geometry['height_min_mm']}..{geometry['height_max_mm']}",
             "the brief states three height units of 7 mm; the base and lip "
             "allowance on top of that is standard-defined and the band is "
             "deliberately wide, because narrowing it would encode the hidden "
             "reference's own total height"),
    ]

    counts = set(got["compartment_ring_counts"])
    want_compartments = geometry["expected_compartments"]
    rows.append(_row(
        "compartment_count", counts == {want_compartments},
        sorted(counts), f"{{{want_compartments}}} at every sampled height",
        "one divider makes two compartments, and it has to be two at every "
        "height in the band -- a divider that stops half way up is a divider "
        "at one sample and not at the next"))

    split = got["split"]
    rows.append(_row(
        "divider_on_long_axis", bool(split) and split["axis"] == geometry["split_axis"],
        split, f"axis {geometry['split_axis']}",
        "the brief asks for the long direction to be split; a divider on the "
        "short axis is one divider in the wrong place, which every count "
        "predicate above would accept"))

    base_bores = max(got["base_ring_counts"], default=0)
    rows.append(_row(
        "no_bores_in_base", base_bores == 0, base_bores, "0",
        "magnet pockets and screw holes are the only reason a closed base "
        "section has a hole in it, and the brief forbids both"))

    areas = got["compartment_cavity_area_mm2"]
    if areas:
        spread = (max(areas) - min(areas)) / max(areas)
    else:
        spread = 1.0
    rows.append(_row(
        "compartment_is_prismatic",
        bool(areas) and spread <= geometry["prismatic_tolerance_fraction"],
        round(spread, 5), f"<= {geometry['prismatic_tolerance_fraction']}",
        "a finger scoop is a ramp at the bottom of a compartment and a label "
        "flange is a tab at the top; both are forbidden and both show up as "
        "the open area changing with height, which a straight-walled "
        "compartment does not"))

    inner = got["compartment_inner_box_mm"]
    lip_inner = got["lip_inner_box_mm"]
    if inner and lip_inner:
        comp_x = max(box[0] for box in inner)
        comp_y = max(box[1] for box in inner)
        top_x = min(box[0] for box in lip_inner)
        top_y = min(box[1] for box in lip_inner)
        inset = min((comp_x - top_x) / 2.0, (comp_y - top_y) / 2.0)
    else:
        inset = 0.0
    rows.append(_row(
        "stack_lip_present", inset >= geometry["min_lip_inset_mm"],
        round(inset, 4), f">= {geometry['min_lip_inset_mm']} mm per side",
        "a stacking lip is a ledge that protrudes inward at the top so the "
        "base of the next bin lands on it, so the opening near the top is "
        "narrower than the compartment below it"))
    return rows


def outer_profile_drift(got: dict[str, Any]) -> float | None:
    """How much the outer cross-section grows between the wall and the rim.

    A **diagnostic**, and it started as a hard predicate. It was demoted for the
    reason section 12 of the brief gives: every predicate that can decide
    PASS/FAIL must have a mutation that proves it can fail, and this one has no
    failure of its own. A rim that flares outward grows the bounding box, so
    `footprint_long_mm` and `footprint_short_mm` already refuse it; a rim that
    grows the cross-section *without* growing the bounding box -- filling the
    corner radii, say -- is 0.35% on this footprint and is not a
    grid-compatibility failure at all. A gate nothing can fail reads exactly
    like one that holds, so it is reported and not gated.
    """
    comp = got["compartment_outer_area_mm2"]
    lip = got["lip_outer_area_mm2"]
    if not comp or not lip:
        return None
    return round(abs(max(lip) - max(comp)) / max(comp), 6)


def comparison_rows(registration: dict[str, Any], geometry: dict[str, Any]
                    ) -> list[dict[str, Any]]:
    band = geometry["reference_comparison"]
    distance = registration["distance"]
    return [
        _row("registration_is_a_proper_rotation",
             registration["determinant"] == 1.0, registration["determinant"],
             "det(R) = +1",
             "translation and a proper rotation only. No scaling and no "
             "reflection is available to the fitter, so a mirrored candidate "
             "is scored as the mismatch it is"),
        _row("reference_surface_distance_p99_mm",
             distance["p99_mm"] <= band["band_mm"],
             round(distance["p99_mm"], 4), f"<= {band['band_mm']} mm",
             "calibrated from same-geometry noise; see the fixture's "
             "calibration block for the method and what it cannot catch"),
    ]


